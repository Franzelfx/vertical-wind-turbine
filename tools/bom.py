#!/usr/bin/env python3
"""Writes docs/bom.md from the KiCad netlist, with stock and price from JLCPCB's public catalogue.

    uv run python tools/bom.py

A dated snapshot, since stock moves: run it by hand after changing parts. Run
tools/build-electronics.sh first, so the netlist is current.
"""

import datetime
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

from jlc_stock import search  # noqa: E402

NETLIST = ROOT / "build" / "kicad" / "charge-board.net.xml"
OUT = ROOT / "docs" / "bom.md"


def groups() -> tuple[list[dict], list[dict]]:
    sourced: dict[str, dict] = {}
    other: dict[tuple, dict] = {}
    for comp in ET.parse(NETLIST).getroot().find("components"):
        ref = comp.get("ref")
        if ref.startswith("H"):
            continue
        fields = {f.get("name"): f.text for f in comp.findall("fields/field")}
        value = comp.findtext("value")
        footprint = comp.findtext("footprint").split(":")[-1]
        code = fields.get("LCSC Part")
        if code:
            sourced.setdefault(code, {"code": code, "value": value, "refs": []})["refs"].append(ref)
        else:
            key = (value, footprint)
            other.setdefault(key, {"value": value, "footprint": footprint, "refs": []})[
                "refs"
            ].append(ref)
    return list(sourced.values()), list(other.values())


def lookup(code: str) -> dict:
    return next((c for c in search(code) if c.get("componentCode") == code), {})


def main() -> None:
    sourced, other = groups()
    lines = [
        "| Parts | Qty | Value | LCSC | Manufacturer's part | Stock | Unit price (USD) | Line |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    total = 0.0
    for item in sorted(sourced, key=lambda g: g["refs"][0]):
        found = lookup(item["code"])
        prices = found.get("componentPrices") or [{}]
        price = float(prices[0].get("productPrice") or 0.0)
        stock = found.get("stockCount") or 0
        qty = len(item["refs"])
        total += qty * price
        shown = f"{stock:,}" if stock else "**none**"
        lines.append(
            f"| {' '.join(sorted(item['refs']))} | {qty} | {item['value']} | {item['code']} "
            f"| {found.get('componentModelEn', '?')} | {shown} | {price:.4f} | {qty * price:.2f} |"
        )
    rest = ["| Parts | Qty | Value | Footprint |", "| --- | --- | --- | --- |"]
    for item in sorted(other, key=lambda g: g["refs"][0]):
        refs = " ".join(sorted(item["refs"]))
        rest.append(f"| {refs} | {len(item['refs'])} | {item['value']} | {item['footprint']} |")
    table = "\n".join(lines)
    rest_table = "\n".join(rest)
    OUT.write_text(f"""# Board parts

> Generated by `tools/bom.py` from the KiCad netlist and JLCPCB's public catalogue; do not edit by hand
> (`tests/test_electronics.py` fails when a part in the schematic is missing here).

Stock and prices as of {datetime.date.today().isoformat()}, single-unit tier.

**Parts total: about {total:.2f} USD per board**, without the fab, assembly, and what is listed below.
Datasheet checks so far: ADR-007.

{table}

## Not at JLCPCB

Hand-fitted, from a distributor. Fuse holders are still open (`plans/electronics.md`, E2).

{rest_table}
""")
    print(f"wrote docs/bom.md: {len(sourced)} lines, about {total:.2f} USD")


if __name__ == "__main__":
    main()
