def assumptions_page() -> str:
    source = (ROOT / "src" / "vawt" / "spec.py").read_text().splitlines()
    rows = ["| Value | Assumption and the test that replaces it |", "| --- | --- |"]
    for line in source:
        match = re.match(r"\s+(\w+): \w+ = ([^#]+?)\s+# ASSUMPTION: (.*)", line)
        if match:
            rows.append(f"| `{match[1]} = {match[2]}` | {match[3]} |")
    return f"""# Assumptions

> Generated by `uv run vawt docs` from the `ASSUMPTION` comments in `src/vawt/spec.py`; do not edit by
> hand (`tests/test_docs.py` fails when this page and the code drift apart).

Each line is a number nobody has measured. `plans/bench.md` names each test.

{chr(10).join(rows)}
"""


def requirements_page() -> str:
    return f"""# Requirements

> Generated by `uv run vawt docs` from `src/vawt/system/requirements.py`; do not edit by hand. Change a
> requirement there. `tests/test_requirements.py` fails when a limit is broken.

Goal: charge a 3S Li-ion pack from a small printed turbine on an 80 x 80 mm, 3 m wooden pier, with
everything needed in one weatherproof enclosure.

Evidence: **M** measured from a real file, **S** from a named source, **E** an estimate. Everything
holds on paper only: nothing has been built yet.

{rq.table()}
"""


def guard_rails() -> str:
    lines = []
    for r in rq.REQUIREMENTS:
        word = "at most" if r.sense == "max" else "at least"
        unit = f" {r.unit}" if r.unit else ""
        lines.append(
            f"- {r.id}: {r.text}: {word} {r.limit:.4g}{unit}; now {r.value():.4g}{unit} "
            f"(holds on [{r.evidence}])."
        )
    return "\n".join(lines)


def key_figures() -> str:
    """The README's table: the figures a visitor looks for first."""
    peak = z.peak_charge()
    start, stop = z.charging_wind_range()
    solar_kwh = YARDSTICK.solar_panel_w * YARDSTICK.solar_kwh_per_kwp / 1000
    holding = sum(r.holds() for r in rq.REQUIREMENTS)
    side = SITE.pier_width
    return f"""| | |
| --- | --- |
| Rotor | {ROTOR.diameter:.0f} x {spec.rotor_height():.0f} mm, printed in ASA |
| Post | {side:.0f} x {side:.0f} mm timber, {SITE.pier_height / 1000:.0f} m tall |
| Battery | {BATTERY.cells_series}S{BATTERY.cells_parallel}P Li-ion, {spec.battery_wh():.0f} Wh, {spec.battery_v_empty():.1f}-{spec.battery_v_full():.1f} V |
| Charges in winds of | {start:.1f} to {stop:.1f} m/s |
| Best output | {peak.charge:.1f} W, at {peak.wind:.0f} m/s |
| Average output | {z.mean_charge_power():.2f} W at an assumed {SITE.mean_wind_m_s} m/s mean wind: {z.annual_energy_kwh():.1f} kWh a year |
| A {YARDSTICK.solar_panel_w:.0f} W solar panel, for scale | about {solar_kwh:.0f} kWh a year |
| Requirements | {holding} of {len(rq.REQUIREMENTS)} hold, on paper |"""


def readme_md(current: str) -> str:
    pattern = re.compile(re.escape(FIGURES_START) + r".*?" + re.escape(FIGURES_END), re.DOTALL)
    return pattern.sub(f"{FIGURES_START}\n{key_figures()}\n{FIGURES_END}", current)


def claude_md(current: str) -> str:
    pattern = re.compile(re.escape(GUARD_START) + r".*?" + re.escape(GUARD_END), re.DOTALL)
    return pattern.sub(f"{GUARD_START}\n{guard_rails()}\n{GUARD_END}", current)


PAGES = {
    "docs/sizing.md": sizing_page,
    "docs/assumptions.md": assumptions_page,
    "plans/requirements.md": requirements_page,
}


def main() -> None:
    for name, page in PAGES.items():
        (ROOT / name).write_text(page())
        print("wrote", name)
    readme = ROOT / "README.md"
    readme.write_text(readme_md(readme.read_text()))
    print("wrote README.md key figures")
    claude = ROOT / "CLAUDE.md"
    if claude.exists():
        claude.write_text(claude_md(claude.read_text()))
        print("wrote CLAUDE.md guard rails")


if __name__ == "__main__":
    main()
