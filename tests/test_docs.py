"""Generated pages stay in sync; paths and ADRs named in Markdown exist; indexes are whole."""

import re
from pathlib import Path

import pytest

from vawt.io import docs

ROOT = Path(__file__).resolve().parents[1]
# The playbook describes another repository: its paths are not ours
MARKDOWN = [
    p
    for p in ROOT.rglob("*.md")
    if not {".venv", "build", ".pytest_cache"} & set(p.parts) and p.name != "PROJECT-PLAYBOOK.md"
]


@pytest.mark.parametrize("name", docs.PAGES)
def test_generated_page_in_sync(name):
    assert (ROOT / name).read_text() == docs.PAGES[name](), f"run `uv run vawt docs` ({name})"


def test_guard_rails_in_sync():
    text = (ROOT / "CLAUDE.md").read_text()
    assert docs.guard_rails() in text, "run `uv run vawt docs`"


def test_readme_figures_in_sync():
    text = (ROOT / "README.md").read_text()
    assert docs.key_figures() in text, "run `uv run vawt docs`"


@pytest.mark.parametrize("path", MARKDOWN, ids=lambda p: str(p.relative_to(ROOT)))
def test_backticked_paths_exist(path):
    missing = []
    for raw in re.findall(r"`([^`\n]+)`", path.read_text()):
        token = raw.split()[0] if " " in raw else raw
        if not re.fullmatch(r"[\w.-]+(/[\w.-]+)+/?", token):
            continue
        if token.startswith(("build/", "http")) or token.endswith((".FCStd", ".3mf")):
            continue  # generated output and the licensed rotor are not committed
        if not (ROOT / token).exists():
            missing.append(token)
    assert not missing, f"{path.name}: {missing}"


@pytest.mark.parametrize("path", MARKDOWN, ids=lambda p: str(p.relative_to(ROOT)))
def test_relative_links_and_images_exist(path):
    """GitHub shows a broken picture or a 404 for these, and nothing else would notice."""
    text = re.sub(r"```.*?```", "", path.read_text(), flags=re.DOTALL)
    targets = re.findall(r"\]\(([^)\s]+)\)", text) + re.findall(r'(?:src|href)="([^"]+)"', text)
    missing = [
        target
        for target in targets
        if not re.match(r"https?:|#|mailto:", target)
        and not (path.parent / target.split("#")[0]).exists()
    ]
    assert not missing, f"{path.name}: {missing}"


@pytest.mark.parametrize("path", MARKDOWN, ids=lambda p: str(p.relative_to(ROOT)))
def test_named_adrs_exist(path):
    decisions = {p.name[:7] for p in (ROOT / "docs" / "decisions").glob("ADR-*.md")}
    for ref in re.findall(r"ADR-\d{3}", path.read_text()):
        assert ref in decisions, f"{path.name} names {ref}"


def test_every_doc_is_in_the_index():
    index = (ROOT / "docs" / "README.md").read_text()
    for page in (ROOT / "docs").glob("*.md"):
        if page.name != "README.md":
            assert page.name in index, page.name
    for page in (ROOT / "docs" / "decisions").glob("ADR-*.md"):
        if "000" not in page.name:
            assert page.name in index, page.name


def test_every_plan_is_in_the_index():
    index = (ROOT / "plans" / "README.md").read_text()
    for page in (ROOT / "plans").glob("*.md"):
        if page.name != "README.md":
            assert page.name in index, page.name


def test_every_doc_page_names_its_source():
    for page in (ROOT / "docs").glob("*.md"):
        if page.name != "README.md":
            assert "Generated by" in page.read_text() or "Written by hand" in page.read_text(), (
                page.name
            )


def test_every_assumption_is_listed_and_names_a_test_or_action():
    source = (ROOT / "src" / "vawt" / "spec.py").read_text()
    count = len(re.findall(r"# ASSUMPTION:", source))
    assert (ROOT / "docs" / "assumptions.md").read_text().count("\n| `") == count
    bench = (ROOT / "plans" / "bench.md").read_text()
    for test in re.findall(r"\bB\d\b", source):
        assert f"**{test}" in bench, f"{test} is named in spec.py but not in plans/bench.md"
